/**
 * Quiz domain types.
 *
 * A quiz is a list of slides produced from one markdown file. Slides are
 * either questions (which students answer) or info slides (projector-only
 * content, e.g. the opening instructions).
 */

/** Allowed choice letters (matches the parser's `A`-`F` rule). */
export type ChoiceLetter = "A" | "B" | "C" | "D" | "E" | "F";

/**
 * Answer type of a question:
 * - `choice`: student picks a `Choice` letter (the default when an answer exists);
 * - `number`: student types a number;
 * - `text`: student types free text.
 */
export type QuestionType = "choice" | "number" | "text";

/** One selectable answer option of a `choice` question. */
export interface Choice {
  /** The the value of this choice. */
  readonly letter: ChoiceLetter;
  /**
   * Option label as markdown, kept verbatim (never rendered here).
   * May be empty (the letter itself will be used instead).
   */
  readonly labelMarkdown: string;
}

/**
 * A slide students must answer within `answerTimeSec`.
 * Markdown bodies are kept verbatim and are rendered only by the UI.
 */
export interface QuestionSlide {
  readonly kind: "question";
  /**
   * Unique question ID (also used as reference inside the database).
   * Taken from the quiz markdown (if specified), otherwise generated by the
   * engine (e.g., "Q1").
   */
  readonly qid: string;
  /** Question prompt as markdown, verbatim. */
  readonly promptMarkdown: string;
  /**
   * Available options, in file order. Populated for `choice` questions;
   * empty for `number`/`text` questions.
   */
  readonly choices: Choice[];
  /**
   * Correct answer: the chosen letter for `choice` questions, the expected
   * value as a string for `number`/`text` questions, or `null` when the
   * quiz author gave none. Never part of public payloads (see public.ts).
   */
  readonly answer: string | null;
  /** Seconds allotted to answer this question (0 - inherited). */
  readonly answerTimeSec: number;
  /**
   * Author-only comment (excluded from displayed payloads)
   */
  readonly comment?: string;
  /** How students answer. Defaults to `choice` when an answer exists. */
  readonly type: QuestionType;
}

/** A projector-only slide (e.g. the opening instructions); no answering. */
export interface InfoSlide {
  readonly kind: "info";
  /** Slide body as markdown, verbatim. */
  readonly promptMarkdown: string;
}

/** One entry of `Quiz.slides`; discriminated on `kind`. */
export type Slide = QuestionSlide | InfoSlide;

/** A fully parsed quiz. */
export interface Quiz {
  /** Quiz identifier from the frontmatter; used to key answers in the DB. */
  readonly id: string;
  /** Display title (waiting screen, admin). */
  readonly title: string;
  /** Default answer time in seconds, applied to questions without an override. */
  readonly defaultAnswerTimeSec: number;
  /** Quiz-level instructions as markdown, verbatim; empty when absent. */
  readonly instructionsMarkdown: string;
  /** Slides in file order. */
  readonly slides: Slide[];
}

/**
 * Public subset of quiz metadata, safe to send to students and the
 * projector. Contains no answers, comments, or question content.
 */
export interface QuizMeta {
  /** Same `id` as {@link Quiz.id}. */
  readonly id: string;
  /** Same `title` as {@link Quiz.title}. */
  readonly title: string;
  /** Total number of questions (info slides excluded). */
  readonly questionCount: number;
}
